"""
deployer.py
AutoMLOps — Dynamic Container Deployment & Lifecycle Management
Author: Ebin Thomas

Handles:
- Allocating free local ports
- Launching / updating serving Docker containers for passing models
- Maintaining model-to-port mapping and status
- Generating and reloading Nginx upstream reverse-proxy routes
- Health checking deployed inference endpoints
"""

import os
import time
import socket
import logging
import subprocess
from typing import Dict, Optional, Any
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("automlops-deployer")

# Global in-memory registry (can be persisted to JSON/SQLite)
# Structure: { model_id: {"port": int, "container_id": str, "container_name": str, "model_path": str, "status": str} }
REGISTRY_FILE = Path(os.getenv("DEPLOY_REGISTRY_FILE", "deployed_registry.json"))
NGINX_CONF_PATH = Path(os.getenv("NGINX_CONF_PATH", "nginx/nginx.conf"))
DEFAULT_IMAGE = os.getenv("SERVING_IMAGE", "automlops-serving")


def find_free_port(start_port: int = 8081, max_port: int = 8999) -> int:
    """Finds an unused TCP port on localhost."""
    for port in range(start_port, max_port):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            try:
                s.bind(("127.0.0.1", port))
                return port
            except OSError:
                continue
    raise RuntimeError(f"No free ports available between {start_port} and {max_port}")


def get_deployed_models() -> Dict[str, Any]:
    """Load registry of currently running or deployed models."""
    if REGISTRY_FILE.exists():
        try:
            import json
            with open(REGISTRY_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as e:
            logger.warning(f"Error reading registry file: {e}")
    return {}


def save_registry(registry: Dict[str, Any]) -> None:
    """Save model registry to disk."""
    import json
    try:
        with open(REGISTRY_FILE, "w", encoding="utf-8") as f:
            json.dump(registry, f, indent=2)
    except Exception as e:
        logger.error(f"Failed to persist deployment registry: {e}")


def update_nginx_config(registry: Dict[str, Any]) -> bool:
    """
    Dynamically generates and reloads Nginx reverse-proxy configuration
    so that /models/{model_id}/predict maps cleanly to the model's container port.
    """
    locations = []
    for model_id, details in registry.items():
        port = details.get("port")
        if port and details.get("status") == "running":
            loc_block = f"""
    location /models/{model_id}/predict {{
        proxy_pass http://host.docker.internal:{port}/predict;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    }}

    location /models/{model_id}/health {{
        proxy_pass http://host.docker.internal:{port}/health;
        proxy_set_header Host $host;
    }}"""
            locations.append(loc_block)

    conf_content = f"""# Auto-generated by AutoMLOps Deployer (Ebin Thomas)
events {{
    worker_connections 1024;
}}

http {{
    include       mime.types;
    default_type  application/octet-stream;
    sendfile        on;
    keepalive_timeout  65;

    server {{
        listen 80;
        server_name localhost;

        location /health {{
            return 200 'AutoMLOps Gateway Healthy\\n';
            add_header Content-Type text/plain;
        }}
{''.join(locations)}
    }}
}}
"""
    try:
        NGINX_CONF_PATH.parent.mkdir(parents=True, exist_ok=True)
        with open(NGINX_CONF_PATH, "w", encoding="utf-8") as f:
            f.write(conf_content)
        logger.info(f"Updated Nginx config at {NGINX_CONF_PATH}")

        # Attempt to reload running nginx container if active
        try:
            subprocess.run(["docker", "exec", "automlops-nginx", "nginx", "-s", "reload"],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
        except Exception:
            pass

        return True
    except Exception as e:
        logger.error(f"Failed to write Nginx configuration: {e}")
        return False


def stop_container(container_name: str) -> None:
    """Safely stop and remove any existing container by name."""
    try:
        subprocess.run(["docker", "stop", container_name],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=15)
        subprocess.run(["docker", "rm", "-f", container_name],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=15)
        logger.info(f"Container {container_name} removed.")
    except Exception as e:
        logger.warning(f"Note on stopping container {container_name}: {e}")


def deploy_model(model_id: str, model_path: str, image_name: str = DEFAULT_IMAGE) -> Dict[str, Any]:
    """
    Deploys or upgrades a model into a Docker serving container.
    Returns deployment information including container name, port, and stable gateway URLs.
    """
    model_abs_path = Path(model_path).resolve()
    if not model_abs_path.exists():
        raise FileNotFoundError(f"Model file not found at {model_abs_path}")

    registry = get_deployed_models()
    container_name = f"automlops_model_{model_id}"

    # If already running, replace container
    if model_id in registry:
        existing = registry[model_id]
        stop_container(existing.get("container_name", container_name))
        port = existing.get("port") or find_free_port()
    else:
        port = find_free_port()

    # Launch Docker container
    # Mount model file directly into /app/model.pkl inside serving container
    docker_cmd = [
        "docker", "run", "-d",
        "--name", container_name,
        "-p", f"{port}:8080",
        "-v", f"{model_abs_path}:/app/model.pkl",
        "-e", "MODEL_PATH=/app/model.pkl",
        "--restart", "unless-stopped",
        image_name
    ]

    logger.info(f"Launching serving container: {' '.join(docker_cmd)}")
    result = subprocess.run(docker_cmd, capture_output=True, text=True)
    if result.returncode != 0:
        logger.error(f"Docker run failed: {result.stderr}")
        raise RuntimeError(f"Failed to start Docker container for model {model_id}: {result.stderr}")

    container_id = result.stdout.strip()

    # Record in registry
    deployment_info = {
        "model_id": model_id,
        "container_id": container_id,
        "container_name": container_name,
        "port": port,
        "model_path": str(model_abs_path),
        "status": "running",
        "direct_url": f"http://localhost:{port}/predict",
        "gateway_url": f"http://localhost/models/{model_id}/predict",
        "health_url": f"http://localhost/models/{model_id}/health",
        "deployed_at": time.strftime("%Y-%m-%d %H:%M:%S")
    }

    registry[model_id] = deployment_info
    save_registry(registry)
    update_nginx_config(registry)

    logger.info(f"Model {model_id} deployed successfully on port {port}. Gateway: {deployment_info['gateway_url']}")
    return deployment_info


def undeploy_model(model_id: str) -> bool:
    """Stops the serving container and removes from registry and Nginx routing."""
    registry = get_deployed_models()
    if model_id not in registry:
        return False

    info = registry.pop(model_id)
    stop_container(info.get("container_name", f"automlops_model_{model_id}"))
    save_registry(registry)
    update_nginx_config(registry)
    return True
